/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the System Power */
  SystemPower_Config();

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_ICACHE_Init();
  MX_LPUART1_UART_Init();
  MX_I2C1_Init();
  /* USER CODE BEGIN 2 */

  /* Initialize COM1 port (115200, 8 bits (7-bit data + 1 stop bit), no parity */
  BspCOMInit.BaudRate   = 115200;
  BspCOMInit.WordLength = COM_WORDLENGTH_8B;
  BspCOMInit.StopBits   = COM_STOPBITS_1;
  BspCOMInit.Parity     = COM_PARITY_NONE;
  BspCOMInit.HwFlowCtl  = COM_HWCONTROL_NONE;
  if (BSP_COM_Init(COM1, &BspCOMInit) != BSP_ERROR_NONE)
  {
    Error_Handler();
  }

  // Use hcom_uart[COM1] now that it is initialized
  char *boot_msg = "\r\n--- UART INITIALIZED ---\r\n";
  HAL_UART_Transmit(&hcom_uart[COM1], (uint8_t*)boot_msg, strlen(boot_msg), 100);

  // 1. Force everything OFF first to clear any "hung" state in the sensor
  HAL_GPIO_WritePin(GPIOA, GPIO_PIN_7, GPIO_PIN_RESET); // Power OFF
  HAL_GPIO_WritePin(GPIOB, GPIO_PIN_0, GPIO_PIN_RESET); // LPn OFF
  HAL_Delay(100);

  // 1. Ensure Power Rail is ON (D11 / PA7)
  HAL_GPIO_WritePin(GPIOA, GPIO_PIN_7, GPIO_PIN_SET);
  HAL_Delay(50);

  // 2. Drive LPn HIGH (A3 / PA4) to wake the I2C logic
  HAL_GPIO_WritePin(GPIOB, GPIO_PIN_0, GPIO_PIN_SET); 
  HAL_Delay(250); // Critical: Wait for the sensor to boot its internal state
  

  HAL_UART_Transmit(&hcom_uart[COM1], (uint8_t*)"Loading VL53L8 Firmware...\r\n", 28, 100);

  dev.platform.address = 0x52;
  dev.platform.hi2c = &hi2c1;

  uint8_t is_alive = 0;
  vl53l8cx_is_alive(&dev, &is_alive);
  sprintf(uart_buf, "is_alive: %d\r\n", is_alive);
  HAL_UART_Transmit(&hcom_uart[COM1], (uint8_t*)uart_buf, strlen(uart_buf), 100);

  HAL_UART_Transmit(&hcom_uart[COM1], (uint8_t*)"Loading firmware...\r\n", 21, 100);

  int8_t status = vl53l8cx_init(&dev);
  if (status != VL53L8CX_STATUS_OK) {
      sprintf(uart_buf, "INIT FAILED: %d\r\n", status);
      HAL_UART_Transmit(&hcom_uart[COM1], (uint8_t*)uart_buf, strlen(uart_buf), 100);
      Error_Handler();
  }

  vl53l8cx_set_resolution(&dev, VL53L8CX_RESOLUTION_8X8);
  vl53l8cx_set_ranging_frequency_hz(&dev, 10);
  vl53l8cx_start_ranging(&dev);

  HAL_UART_Transmit(&hcom_uart[COM1], (uint8_t*)"Ranging started\r\n", 17, 100);
  

  /* USER CODE END 2 */

  /* Initialize leds */
  BSP_LED_Init(LED_GREEN);
  BSP_LED_Init(LED_BLUE);
  BSP_LED_Init(LED_RED);

  /* Initialize USER push-button, will be used to trigger an interrupt each time it's pressed.*/
  BSP_PB_Init(BUTTON_USER, BUTTON_MODE_EXTI);

  /* Initialize COM1 port (115200, 8 bits (7-bit data + 1 stop bit), no parity */
  BspCOMInit.BaudRate   = 115200;
  BspCOMInit.WordLength = COM_WORDLENGTH_8B;
  BspCOMInit.StopBits   = COM_STOPBITS_1;
  BspCOMInit.Parity     = COM_PARITY_NONE;
  BspCOMInit.HwFlowCtl  = COM_HWCONTROL_NONE;
  if (BSP_COM_Init(COM1, &BspCOMInit) != BSP_ERROR_NONE)
  {
    Error_Handler();
  }

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {

    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
    uint8_t is_ready = 0;
    vl53l8cx_check_data_ready(&dev, &is_ready);
    if (is_ready) {
        vl53l8cx_get_ranging_data(&dev, &results);
        BSP_LED_Toggle(LED_GREEN);

        // CSV frame: FRAME,<tick_ms>,<d0..d15>,<sig0..sig15>,<status0..status15>
        int len = sprintf(uart_buf, "FRAME,%lu", HAL_GetTick());
        HAL_UART_Transmit(&hcom_uart[COM1], (uint8_t*)uart_buf, len, 100);

        for (int i = 0; i < 64; i++) {
            len = sprintf(uart_buf, ",%d", results.distance_mm[VL53L8CX_NB_TARGET_PER_ZONE * i]);
            HAL_UART_Transmit(&hcom_uart[COM1], (uint8_t*)uart_buf, len, 100);
        }
        for (int i = 0; i < 64; i++) {
            len = sprintf(uart_buf, ",%lu", results.signal_per_spad[VL53L8CX_NB_TARGET_PER_ZONE * i]);
            HAL_UART_Transmit(&hcom_uart[COM1], (uint8_t*)uart_buf, len, 100);
        }
        for (int i = 0; i < 64; i++) {
            len = sprintf(uart_buf, ",%u", results.target_status[VL53L8CX_NB_TARGET_PER_ZONE * i]);
            HAL_UART_Transmit(&hcom_uart[COM1], (uint8_t*)uart_buf, len, 100);
        }
        HAL_UART_Transmit(&hcom_uart[COM1], (uint8_t*)"\r\n", 2, 100);
    }
    HAL_Delay(10);
  }
  /* USER CODE END 3 */
}

